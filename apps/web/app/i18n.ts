export function translate(locale: Locale, key: TranslationKey, values: TranslationValues = {}) {
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    translations[locale][key],
  );
}

export function isSupportedLocale(value: string | null | undefined): value is Locale {
  return Boolean(value && supportedLocales.includes(value as Locale));
}

export function detectBrowserLocale(languages: readonly string[] = []): Locale {
  for (const language of languages) {
    const normalized = language.toLowerCase().replace("_", "-");
    const exact = normalized.split("-")[0];
    if (isSupportedLocale(exact)) return exact;
  }
  return "de";
}

export function readLocaleCookie(cookieString: string | undefined): Locale | null {
  const cookie = cookieString?.split(";").map((part) => part.trim()).find((part) => part.startsWith("wagi_locale="));
  const value = cookie?.slice("wagi_locale=".length);
  return isSupportedLocale(value) ? value : null;
}

export function writeLocaleCookie(locale: Locale) {
  document.cookie = `wagi_locale=${locale}; Max-Age=31536000; Path=/; SameSite=Lax`;
}
